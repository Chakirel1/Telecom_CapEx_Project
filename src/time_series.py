import numpy as np
import matplotlib.pyplot as plt
from statsmodels.tsa.arima.model import ARIMA


# On garde tout SAUF les 4 derniers trimestres pour l'entraînement
train_log = df_reel['Trafic_Log'].iloc[:-4].dropna()

# On garde UNIQUEMENT les 4 derniers trimestres (en vrais Téraoctets) pour le test final
test_reel = df_reel['Trafic_To'].iloc[-4:]

print(f" Phase d'apprentissage sur : {len(train_log)} trimestres")
print(f" Phase de test (données cachées) sur : {len(test_reel)} trimestres\n")

# ---------------------------------------------------------
# 2. L'ENTRAÎNEMENT & LA PRÉDICTION
# ---------------------------------------------------------
modele_test = ARIMA(train_log, order=(1, 1, 1))
resultats_test = modele_test.fit()

previsions_log_test = resultats_test.forecast(steps=4)

previsions_reelles_test = np.exp(previsions_log_test)

# ---------------------------------------------------------
# 3. LE CALCUL DU SCORE (MAPE)
# ---------------------------------------------------------
erreurs_absolues = np.abs((test_reel.values - previsions_reelles_test.values) / test_reel.values)
mape = np.mean(erreurs_absolues) * 100
fiabilite = 100 - mape

print("---  VERDICT DU BACKTESTING ---")
print(f"Marge d'erreur moyenne (MAPE) : {mape:.2f} %")
print(f"Fiabilité du modèle ARIMA    : {fiabilite:.2f} %\n")

plt.figure(figsize=(12, 6))

plt.plot(df_reel.index[:-4], df_reel['Trafic_To'].iloc[:-4], label="Passé (Données d'entraînement)", color='#1f77b4', marker='o')

plt.plot(test_reel.index, test_reel, label="Réalité (Ce qu'il fallait trouver)", color='green', marker='o', linewidth=2.5)

plt.plot(previsions_reelles_test.index, previsions_reelles_test, label="Prédiction de l'ARIMA", color='red', marker='X', linestyle='--', linewidth=2.5)

plt.title(f"Test de Fiabilité - Précision à {fiabilite:.2f}%", fontsize=16, fontweight='bold')
plt.xlabel("Années")
plt.ylabel("Volume (Téraoctets)")
plt.legend(fontsize=11)
plt.grid(True, linestyle='--', alpha=0.6)
plt.show()

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from statsmodels.tsa.arima.model import ARIMA

print(" Lancement des prévisions officielles pour 2026-2027...")

# ---------------------------------------------------------
# 1. ENTRAÎNEMENT SUR 100% DES DONNÉES
# ---------------------------------------------------------
# On utilise toute la série Log pour un maximum d'intelligence
modele_final = ARIMA(df_reel['Trafic_Log'].dropna(), order=(1, 1, 1))
resultats_finaux = modele_final.fit()

# ---------------------------------------------------------
# 2. PRÉDICTION SUR 2 ANS (8 trimestres)
# ---------------------------------------------------------
horizon = 8
previsions_detaillees = resultats_finaux.get_forecast(steps=horizon)

#  L'Antidote (Exponentielle) pour repasser en Téraoctets
previsions_moyennes = np.exp(previsions_detaillees.predicted_mean)
marges_erreur = previsions_detaillees.conf_int()
borne_basse = np.exp(marges_erreur.iloc[:, 0])
borne_haute = np.exp(marges_erreur.iloc[:, 1])

# ---------------------------------------------------------
# 3. EXPORTATION DES DONNÉES
# ---------------------------------------------------------
tableau_final = pd.DataFrame({
    'Prevision_To': previsions_moyennes.round(0), # On arrondit pour faire propre
    'Borne_Basse_To': borne_basse.round(0),
    'Borne_Haute_To': borne_haute.round(0)
})

print("\n Aperçu des futurs volumes à prévoir :")
print(tableau_final.head())

# Sauvegarde physique du fichier
tableau_final.to_csv('Previsions_Trafic_2026_2027.csv')
print("\n Fichier 'Previsions_Trafic_2026_2027.csv' sauvegardé avec succès dans tes dossiers !")

# ---------------------------------------------------------
