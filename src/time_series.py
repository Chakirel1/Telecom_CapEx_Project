# --- ÉTAPE 6 : DIAGNOSTIC DES RÉSIDUS (Validation du modèle) ---
import matplotlib.pyplot as plt
import scipy.stats as stats
import seaborn as sns
from statsmodels.graphics.tsaplots import plot_acf
from statsmodels.stats.diagnostic import acorr_ljungbox


resid = resultats_finaux.resid

fig, ax = plt.subplots(2, 2, figsize=(15, 10))

ax[0, 0].plot(resid)
ax[0, 0].set_title('1. Graphique des Résidus (Doit être plat et aléatoire)')
ax[0, 0].axhline(0, color='red', linestyle='--')

sns.histplot(resid, kde=True, ax=ax[0, 1], color='blue')
ax[0, 1].set_title('2. Distribution (Doit suivre une courbe en cloche/Normale)')

plot_acf(resid, ax=ax[1, 0], lags=20)
ax[1, 0].set_title('3. Autocorrélation des résidus (ACF)')

stats.probplot(resid, dist="norm", plot=ax[1, 1])
ax[1, 1].set_title('4. QQ-Plot')

plt.tight_layout()
plt.show()

# --- TEST STATISTIQUE DE LJUNG-BOX ---
print("--- Résultat du test de Ljung-Box ---")
ljung_box_results = acorr_ljungbox(resid, lags=[10], return_df=True)
print(ljung_box_results)
print("\nInterprétation : Si la p-value est > 0.05, les résidus sont indépendants (Le modèle est parfait).")
