import numpy as np
import matplotlib.pyplot as plt
from statsmodels.tsa.stattools import adfuller

print("--- TEST DE STATIONNARITÉ (Série brute) ---")
resultat_brut = adfuller(df_reel['Trafic_To'].dropna())
print(f"Le p-value est de : {resultat_brut[1]:.5f}")


df_reel['Trafic_Log'] = np.log(df_reel['Trafic_To'])

# 2. On annule la montée avec la differenciation
df_reel['Trafic_Stationnaire'] = df_reel['Trafic_Log'].diff()

# 3. On nettoie la case vide
donnees_propres = df_reel['Trafic_Stationnaire'].dropna()

# 4. On relance le scanner sur les bonnes données
print("\n--- TEST DE STATIONNARITÉ (Série Transformée) ---")
resl = adfuller(donnees_propres)
p_value_1 = resl[1]

print(f"Le nouveau p-value est de : {p_value_1:.5f}")

if p_value_1 <= 0.05:
    print("Verdict :  La série est prête (Stationnaire) !")
else:
    print("Verdict :  La série n'est PAS stationnaire.")


plt.figure(figsize=(12, 5))
plt.plot(df_reel.index, df_reel['Trafic_Stationnaire'], marker='o', color='green', linewidth=2)
plt.title("Série Parfaitement Stationnaire (Log + Diff)", fontsize=14)
plt.axhline(y=0, color='red', linestyle='--')
plt.xlabel("Années")
plt.ylabel("Variation du Log(Volume)")
plt.grid(True, linestyle='--', alpha=0.7)
